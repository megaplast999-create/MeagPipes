class TestExcelExportParityAndProperties:
    """Verifies Task 6 criteria comparing web export to desktop export."""

    def test_amount_in_words_accuracy(self):
        """Verifies Indian currency word conversion against golden baselines."""
        words_1786 = number_to_indian_words(178657900.0)
        assert words_1786 == "Rupees Seventeen Crore Eighty Six Lakh Fifty Seven Thousand Nine Hundred Only"

        words_1761 = number_to_indian_words(176117500.0)
        assert words_1761 == "Rupees Seventeen Crore Sixty One Lakh Seventeen Thousand Five Hundred Only"

        words_zero = number_to_indian_words(0.0)
        assert words_zero == "Rupees Zero Only"

    def test_compare_sheet_names_and_structure(self, unipro_golden_quotation):
        """Web export must have identical sheet names to verified desktop export."""
        quote, calc = unipro_golden_quotation
        web_stream = ExcelExportService.generate_quotation_workbook(quote, calc)

        wb_web = openpyxl.load_workbook(web_stream)
        wb_desktop = openpyxl.load_workbook(str(DESKTOP_EXPORT_PATH))

        # Both must contain OFFER and Synopsis sheets
        assert set(wb_web.sheetnames) == {"OFFER", "Synopsis"}
        assert set(wb_desktop.sheetnames) == {"OFFER", "Synopsis"}

    def test_compare_protection_and_passwords(self, unipro_golden_quotation):
        """Neither workbook may contain worksheet protection, workbook protection, or passwords."""
        quote, calc = unipro_golden_quotation
        web_stream = ExcelExportService.generate_quotation_workbook(quote, calc)

        wb_web = openpyxl.load_workbook(web_stream)
        wb_desktop = openpyxl.load_workbook(str(DESKTOP_EXPORT_PATH))

        # Workbook-level protection disabled
        assert wb_web.security.lockStructure is False
        assert wb_web.security.lockWindows is False
        assert wb_desktop.security is None or wb_desktop.security.lockStructure is False

        # Sheet-level protection disabled on all sheets
        for sname in ["OFFER", "Synopsis"]:
            assert wb_web[sname].protection.sheet is False, f"Web sheet {sname} is protected"
            assert wb_desktop[sname].protection.sheet is False, f"Desktop sheet {sname} is protected"

        # Web export explicitly unlocks all populated cells
        ws_web_offer = wb_web["OFFER"]
        for row in ws_web_offer.iter_rows(min_row=1, max_row=ws_web_offer.max_row, min_col=1, max_col=ws_web_offer.max_column):
            for cell in row:
                if cell.value is not None:
                    assert cell.protection.locked is False, f"Cell {cell.coordinate} is locked"

    def test_compare_totals_and_amount_in_words(self, unipro_golden_quotation):
        """Line items, grand totals, and amount in words must match desktop export."""
        quote, calc = unipro_golden_quotation
        web_stream = ExcelExportService.generate_quotation_workbook(quote, calc)

        wb_web = openpyxl.load_workbook(web_stream, data_only=True)
        wb_desktop = openpyxl.load_workbook(str(DESKTOP_EXPORT_PATH), data_only=True)

        ws_web = wb_web["OFFER"]
        ws_desk = wb_desktop["OFFER"]

        # Desktop reference subtotal at H12: 178,657,900
        desktop_subtotal = ws_desk["H12"].value
        assert desktop_subtotal == 178657900

        # Web export subtotal calculated value
        assert calc["subtotal_excl_gst"] == 178657900.0

        # Line items check: 4 lines
        # Desktop lines are at rows 8, 9, 10, 11
        # Web lines are at rows 9, 10, 11, 12
        for i in range(4):
            desk_qty = ws_desk.cell(row=8 + i, column=6).value
            desk_rate = ws_desk.cell(row=8 + i, column=7).value
            desk_total = ws_desk.cell(row=8 + i, column=8).value

            web_qty = ws_web.cell(row=9 + i, column=6).value
            web_rate = ws_web.cell(row=9 + i, column=8).value

            assert web_qty == desk_qty
            assert web_rate == desk_rate
            # Line value: quantity * rate
            assert (web_qty * web_rate) == desk_total

        # Amount in Words check
        desk_words = str(ws_desk["A13"].value).strip()
        web_words = str(ws_web["A17"].value).strip()
        expected_words = "Total Amount in Words: Rupees Seventeen Crore Eighty Six Lakh Fifty Seven Thousand Nine Hundred Only"
        assert desk_words == expected_words
        assert web_words == expected_words

    def test_formula_integrity_and_zero_external_links(self, unipro_golden_quotation):
        """Web export formulas must be purely local and free of external brackets or broken tokens."""
        quote, calc = unipro_golden_quotation
        web_stream = ExcelExportService.generate_quotation_workbook(quote, calc)

        wb_web = openpyxl.load_workbook(web_stream, data_only=False)
        ws_offer = wb_web["OFFER"]

        # Line 1-4 formulas: =F{r}*H{r}
        for r in range(9, 13):
            formula = str(ws_offer[f"I{r}"].value)
            assert formula == f"=F{r}*H{r}", f"Line formula mismatch at row {r}: {formula}"

        # Subtotal formula: =SUM(I9:I12)
        assert str(ws_offer["I13"].value) == "=SUM(I9:I12)"

        # GST formula: =ROUND(I13*0.18, 0)
        assert str(ws_offer["I14"].value) == "=ROUND(I13*0.18, 0)"

        # Grand Total formula: =I13+I14
        assert str(ws_offer["I15"].value) == "=I13+I14"

        # Check all cells across all sheets for external links or broken tokens
        for ws in wb_web.worksheets:
            for row in ws.iter_rows():
                for cell in row:
                    val = str(cell.value or "")
                    if val.startswith("="):
                        assert "[" not in val and "]" not in val, f"External bracket link in {ws.title}!{cell.coordinate}: {val}"
                        assert ".xlsm" not in val, f"External workbook link in {ws.title}!{cell.coordinate}: {val}"
                        assert "#REF!" not in val, f"Broken REF in {ws.title}!{cell.coordinate}: {val}"
                        assert "#NAME?" not in val, f"Broken NAME in {ws.title}!{cell.coordinate}: {val}"

    def test_open_edit_save_reopen_lifecycle(self, unipro_golden_quotation, tmp_path):
        """Verifies user can open the generated workbook, edit any cell, save, and reopen cleanly."""
        quote, calc = unipro_golden_quotation
        web_stream = ExcelExportService.generate_quotation_workbook(quote, calc)

        test_file = tmp_path / "customer_quotation_editable.xlsx"
        test_file.write_bytes(web_stream.getvalue())

        # 1. Open with openpyxl
        wb = openpyxl.load_workbook(str(test_file))
        ws_offer = wb["OFFER"]

        # 2. Edit quantity and unit rate
        original_qty = ws_offer["F9"].value
        original_rate = ws_offer["H9"].value
        assert original_qty == 2000
        assert original_rate == 22681

        ws_offer["F9"].value = 2500
        ws_offer["H9"].value = 23000
        ws_offer["A17"].value = "Total Amount in Words: Rupees Custom Edited Amount Only"
        ws_offer["B4"].value = "Edited Customer Name International"

        # 3. Save modified workbook
        saved_file = tmp_path / "customer_quotation_modified.xlsx"
        wb.save(str(saved_file))

        # 4. Reopen and verify persistence
        wb_reopened = openpyxl.load_workbook(str(saved_file))
        ws_reopened = wb_reopened["OFFER"]

        assert ws_reopened["F9"].value == 2500
        assert ws_reopened["H9"].value == 23000
        assert ws_reopened["A17"].value == "Total Amount in Words: Rupees Custom Edited Amount Only"
        assert ws_reopened["B4"].value == "Edited Customer Name International"

        # Ensure protection remains disabled after save and reopen
        assert wb_reopened.security.lockStructure is False
        assert ws_reopened.protection.sheet is False
        assert ws_reopened["F9"].protection.locked is False
        assert ws_reopened["H9"].protection.locked is False

        # Ensure formula at I9 remained intact
        assert str(ws_reopened["I9"].value) == "=F9*H9"
